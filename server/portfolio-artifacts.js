export function writeWardCaseStudyArtifacts(rootDir) {
  const generatedAt = new Date().toISOString()
  const outputDir = join(rootDir, ...CASE_STUDY_DIR.split('/'))
  mkdirSync(outputDir, { recursive: true })

  const artifacts = [
    {
      filename: 'ward-agent-studio-case-study.md',
      label: 'Full Case Study',
      description: 'Problem, solution, features, stack, demo flow, CV bullets, internship angle, and roadmap.',
      content: caseStudyMarkdown(generatedAt),
    },
    {
      filename: 'ward-agent-studio-readme-section.md',
      label: 'README Section Draft',
      description: 'GitHub-ready summary text Ward can paste into the main README.',
      content: readmeSectionMarkdown(generatedAt),
    },
    {
      filename: 'ward-agent-studio-recruiter-notes.md',
      label: 'CV and Internship Notes',
      description: 'Short portfolio card copy plus CV and internship-friendly bullets.',
      content: recruiterMarkdown(generatedAt),
    },
  ]

  const written = artifacts.map(artifact => {
    const relativePath = `${CASE_STUDY_DIR}/${artifact.filename}`
    writeFileSync(join(rootDir, relativePath), artifact.content, 'utf8')
    return {
      path: relativePath,
      label: artifact.label,
      description: artifact.description,
    }
  })

  const manifest = {
    generatedAt,
    summary: 'Case study mission wrote real markdown artifacts into docs/case-study.',
    artifacts: written,
  }
  const manifestPath = `${CASE_STUDY_DIR}/ward-agent-studio-output.json`
  writeFileSync(join(rootDir, manifestPath), JSON.stringify(manifest, null, 2), 'utf8')

  return {
    ...manifest,
    artifacts: [
      ...written,
      {
        path: manifestPath,
        label: 'Artifact Manifest',
        description: 'Machine-readable list of generated mission outputs.',
      },
    ],
  }
}
